"""Build data/calls.js from data/sources/{calls,tags}.yaml.

Hand-edited YAML -> a generated JS file assigning window globals, so the frontend works
via file:// with no dev server (avoids fetch() CORS issues on file://). Never hand-edit
data/calls.js — it's gitignored and regenerated by this script (and, at deploy time, by
.github/workflows/deploy.yml).
"""
import argparse
import json
import sys

import yaml

import validate as validator

CALLS_PATH = "data/sources/calls.yaml"
TAGS_PATH = "data/sources/tags.yaml"
OUTPUT_PATH = "data/calls.js"


def load():
    return validator.load_yaml(CALLS_PATH), validator.load_yaml(TAGS_PATH)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="validate only, do not write data/calls.js")
    args = parser.parse_args()

    try:
        calls, tags_doc = load()
    except yaml.YAMLError as e:
        print(f"ERROR: could not parse YAML: {e}")
        sys.exit(1)

    errors, warnings = validator.validate(calls, tags_doc)

    for w in warnings:
        print(f"WARNING: {w}")
    for e in errors:
        print(f"ERROR: {e}")
    if errors:
        print(f"\n{len(errors)} error(s), {len(warnings)} warning(s). Not writing {OUTPUT_PATH}.")
        sys.exit(1)

    if args.check:
        print(f"OK: {len(calls)} entries valid ({len(warnings)} warning(s)). --check: not writing {OUTPUT_PATH}.")
        return

    with open(OUTPUT_PATH, "w", encoding="utf-8") as f:
        f.write("// GENERATED by build.py from data/sources/*.yaml — do not hand-edit.\n")
        f.write(f"window.CALLS = {json.dumps(calls, ensure_ascii=False, default=str)};\n")
        f.write(f"window.TAGS = {json.dumps(tags_doc, ensure_ascii=False, default=str)};\n")
    print(f"built {len(calls)} calls -> {OUTPUT_PATH} ({len(warnings)} warning(s))")


if __name__ == "__main__":
    main()
